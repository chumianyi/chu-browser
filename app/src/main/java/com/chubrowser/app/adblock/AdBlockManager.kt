    private suspend fun downloadAndParseRules(url: String) = withContext(Dispatchers.IO) {
        try {
            val connection = URL(url).openConnection()
            connection.connectTimeout = 10000
            connection.readTimeout = 30000
            val reader = BufferedReader(InputStreamReader(connection.getInputStream()))
            var line: String?
            while (reader.readLine().also { line = it } != null) {
                val rule = line!!.trim()
                if (rule.isEmpty() || rule.startsWith("!") || rule.startsWith("[")) continue
                if (rule.startsWith("||") && rule.endsWith("^")) {
                    val domain = rule.removePrefix("||").removeSuffix("^")
                    blockedDomains.add(domain)
                }
            }
            reader.close()
        } catch (e: Exception) {
            Log.w(TAG, "Failed to parse rules from $url: ${e.message}")
        }
    }

