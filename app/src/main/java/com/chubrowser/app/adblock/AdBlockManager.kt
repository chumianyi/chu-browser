            val cleanHost = host.removePrefix("www.")

            // 检查域名
            if (blockedDomains.any { cleanHost == it || cleanHost.endsWith(".$it") }) {
                blockedCount++
                return true
            }

            // 检查URL模式
            if (blockedUrlPatterns.any { it.matches(url) }) {
                blockedCount++
                return true
            }

            false
        } catch (e: Exception) {
            false
        }
    }

    fun isWhitelisted(url: String): Boolean {
        return try {
            val host = java.net.URI(url).host ?: return false
            val cleanHost = host.removePrefix("www.")
            whitelist.any { cleanHost == it || cleanHost.endsWith(".$it") }
        } catch (e: Exception) {
            false
        }
    }

    fun addToWhitelist(domain: String) {
        whitelist.add(domain.removePrefix("www."))
    }

    fun removeFromWhitelist(domain: String) {
        whitelist.remove(domain.removePrefix("www."))
    }

    fun getWhitelist(): Set<String> = whitelist.toSet()

    fun getBlockedCount(): Int = blockedCount

    fun resetBlockedCount() {
        blockedCount = 0
    }

    fun getBlockedDomainsCount(): Int = blockedDomains.size

    fun getBlockedPatternsCount(): Int = blockedUrlPatterns.size

    fun isInitialized(): Boolean = initialized
}
